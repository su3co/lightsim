/// Compile and run a simulation on the CPU reference backend.
pub fn run_cpu(sim: &Simulation) -> anyhow::Result<Results> {
    let plan = compile(sim, &CompileOptions::default())?;
    let be = engine::cpu::CpuBackend::new(plan)?;
    run::run_backend(Box::new(be), &run::RunOptions::default())
}

/// Run on the CPU reference backend split into `nslabs` x-slabs. Exercises the
/// domain-decomposition halo exchange (incl. Bloch wraps) without GPUs.
pub fn run_cpu_slabs(sim: &Simulation, nslabs: usize) -> anyhow::Result<Results> {
    let grid = sim.build_grid()?;
    let parts = plan::decompose_x(grid.n()[0], &vec![1.0; nslabs]);
    let mut slabs: Vec<Box<dyn Backend>> = Vec::new();
    for (r, &(x0, nxl)) in parts.iter().enumerate() {
        let opts = CompileOptions { slab: Some((x0, nxl)), nslabs, slab_index: r, ..Default::default() };
        slabs.push(Box::new(engine::cpu::CpuBackend::new(plan::compile_with_grid(sim, grid.clone(), &opts)?)?));
    }
    let mut chain = run::Chain::new(slabs);
    chain.local_wrap = nslabs > 1 && sim.boundaries.x[0].is_periodic();
    run::run_chain(&mut chain, &run::RunOptions::default())
}
