//! # lightsim-core
//!
//! GPU-first finite-difference time-domain (FDTD) electromagnetic solver.
//! This crate holds the backend-independent pieces:
//!
//! * [`spec`] — the serializable simulation description (what the Python API
//!   and the CLI produce),
//! * [`grid`], [`materials`], [`geometry`], [`raster`] — meshing, material
//!   models and sub-pixel-smoothed rasterization,
//! * [`sources`], [`monitors`] — source and monitor definitions,
//! * [`plan`] — compilation into a backend-independent execution plan,
//! * [`engine`] — the backend trait and the multithreaded CPU reference
//!   backend,
//! * [`run`] — single/multi-slab and multi-process time-stepping drivers,
//! * [`results`] — result assembly and post-processing.
//!
//! GPU execution lives in `lightsim-cuda` (kernels written in Rust and compiled
//! with NVIDIA cuda-oxide).
//!
//! [`autodiff`] computes gradients with respect to a design region inside
//! the engine (persistent S-matrix sessions, reverse mode through the time
//! loop).

