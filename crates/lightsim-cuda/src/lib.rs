/// PTX generated by `scripts/build_kernels.sh` (cuda-oxide).
pub const KERNELS_PTX: &str = include_str!("../ptx/lightsim_kernels.ptx");

/// The PTX to load: the built-in one, or the file named by `LIGHTSIM_PTX`
/// (kernel development: try a rebuilt or patched PTX without relinking).
fn kernels_ptx() -> std::borrow::Cow<'static, str> {
    match std::env::var("LIGHTSIM_PTX").ok().and_then(|p| std::fs::read_to_string(p).ok()) {
        Some(src) => src.into(),
        None => KERNELS_PTX.into(),
    }
}

/// Kernel argument slots (each 8 bytes; 32-bit values in the low bytes).
struct Args(Vec<u64>);

impl Args {
    fn new() -> Args {
        Args(Vec::with_capacity(32))
    }
    fn p(mut self, v: u64) -> Args {
        self.0.push(v);
        self
    }
    fn u(mut self, v: u32) -> Args {
        self.0.push(v as u64);
        self
    }
    fn u64(mut self, v: u64) -> Args {
        self.0.push(v);
        self
    }
    fn f(mut self, v: f32) -> Args {
        self.0.push(v.to_bits() as u64);
        self
    }
}

