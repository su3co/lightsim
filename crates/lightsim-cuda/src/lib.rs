//! # lightsim-cuda
//!
//! CUDA backend for lightsim. The device kernels are written in Rust in
//! `kernels/` and compiled to PTX by NVIDIA's cuda-oxide backend; this crate
//! embeds that PTX, loads it through `cuda-core` and drives it. Everything
//! (fields, coefficients, CPML auxiliaries, source tables, DFT accumulators,
//! time-monitor buffers) lives on the device; the host only enqueues kernels.
//!
//! * [`CudaBackend`] — one GPU, one x-slab. Grids that are one periodic
//!   cell thick along an axis (2-D problems) run their own step kernel on
//!   the field sets in use (`twod`).
//! * [`multi::MultiGpu`] — several GPUs in one process with peer-to-peer
//!   halo exchange, presented to the drivers as a single backend.

