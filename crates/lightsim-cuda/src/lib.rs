impl CudaBackend {
    pub fn context(&self) -> &Arc<CudaContext> {
        &self.ctx
    }
    pub fn stream(&self) -> &Arc<CudaStream> {
        &self.stream
    }
    pub fn ordinal(&self) -> usize {
        self.ordinal
    }

    /// Device pointer of a field component (storage layout, current buffers).
    pub fn field_ptr(&self, c: Component) -> u64 {
        if c.is_e() { self.e[c.axis()].cu_deviceptr() } else { self.h[c.axis()].cu_deviceptr() }
    }

    /// Pointer of the buffer that receives the new values during a step
    /// (B buffers in fused mode, the current buffers otherwise).
    fn new_ptr(&self, c: Component) -> u64 {
        match &self.fused {
            Some(f) => {
                if c.is_e() { f.eb[c.axis()].cu_deviceptr() } else { f.hb[c.axis()].cu_deviceptr() }
            }
            None => self.field_ptr(c),
        }
    }

    /// As [`new_ptr`](Self::new_ptr) for the imaginary part of complex
    /// fields (the part not currently selected).
    fn new_ptr_imag(&self, c: Component) -> u64 {
        let Some(cx) = &self.cplx else { return self.dummy.cu_deviceptr() };
        let ax = c.axis();
        match (self.fused.as_ref().and_then(|f| f.imag.as_ref()), c.is_e()) {
            (Some(im), true) => im.eb[ax].cu_deviceptr(),
            (Some(im), false) => im.hb[ax].cu_deviceptr(),
            (None, true) => cx.e[ax].cu_deviceptr(),
            (None, false) => cx.h[ax].cu_deviceptr(),
        }
    }

    /// Buffer used for halo exchange of a component during a step: E is
    /// exchanged before the (fused) update from the current buffers, H after
    /// it from the new buffers.
    fn halo_ptr(&self, c: Component) -> u64 {
        if c.is_e() { self.field_ptr(c) } else { self.new_ptr(c) }
    }

    /// True if this backend runs the fused single-kernel step.
    pub fn is_fused(&self) -> bool {
        self.fused.is_some()
    }

    /// Number of distinct material coefficient sets (fused mode).
    pub fn material_count(&self) -> usize {
        self.fused.as_ref().map(|f| f.n_materials).unwrap_or(0)
    }

    /// Byte offset of an x plane (storage plane index 0..=nxl+1).
    pub fn plane_offset(&self, storage_plane: usize) -> u64 {
        (storage_plane * self.plan.plane() * 4) as u64
    }

}

/// Number of visible CUDA devices.
pub fn device_count() -> Result<usize> {
    Ok(CudaContext::device_count()? as usize)
}

/// Compile and run a simulation on one GPU.
pub fn run_gpu(sim: &lightsim_core::Simulation, ordinal: usize) -> Result<lightsim_core::Results> {
    let plan = lightsim_core::compile(sim, &lightsim_core::CompileOptions::default())?;
    let be = CudaBackend::new(plan, ordinal)?;
    lightsim_core::run::run_backend(Box::new(be), &lightsim_core::run::RunOptions::default())
}

/// Measure achievable device memory bandwidth (GB/s) with the `scale_copy`
/// kernel (read + write of `mb` MiB), best of 5.
pub fn membw(ordinal: usize, mb: usize) -> Result<f64> {
    let ctx = CudaContext::new(ordinal)?;
    let stream = ctx.new_stream()?;
    let module = ctx.load_module_from_ptx_src(&kernels_ptx())?;
    let f = module.load_function("scale_copy")?;
    let n = mb * 1024 * 1024 / 4;
    let a = DeviceBuffer::<f32>::zeroed(&stream, n)?;
    let b = DeviceBuffer::<f32>::zeroed(&stream, n)?;
    let mut best = 0.0f64;
    for _ in 0..5 {
        let t0 = std::time::Instant::now();
        let mut slots = vec![b.cu_deviceptr(), a.cu_deviceptr(), n as u64, (1.0f32).to_bits() as u64];
        let mut ptrs: Vec<*mut c_void> = slots.iter_mut().map(|s| s as *mut u64 as *mut c_void).collect();
        let g = (n as u64).div_ceil(256) as u32;
        unsafe { launch_kernel_on_stream(&f, (g, 1, 1), (256, 1, 1), 0, &stream, &mut ptrs) }.map_err(|e| anyhow!("{e:?}"))?;
        stream.synchronize()?;
        let dt = t0.elapsed().as_secs_f64();
        best = best.max(2.0 * (n * 4) as f64 / dt / 1e9);
    }
    Ok(best)
}
