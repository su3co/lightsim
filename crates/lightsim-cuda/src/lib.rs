    /// Gain cells: P update from E^n (before the E update).
    fn gain_pre_launch(&self) -> Result<()> {
        let Some((tab, comps)) = &self.gain else { return Ok(()) };
        for c in comps {
            if self.idle_2d(c.comp) {
                continue;
            }
            let args = Args::new()
                .p(self.field_ptr(c.comp))
                .p(c.idx.cu_deviceptr())
                .p(c.row.cu_deviceptr())
                .p(tab.cu_deviceptr())
                .p(c.pop.cu_deviceptr())
                .p(c.prev.cu_deviceptr())
                .p(c.p.cu_deviceptr())
                .p(c.pp.cu_deviceptr())
                .p(c.dp.cu_deviceptr())
                .u(c.n as u32);
            self.launch_1d(&self.k.gain_pre, c.n, args)?;
        }
        Ok(())
    }

    /// Gain cells: E^{n+1} -= scale dP and the population update.
    fn gain_post_launch(&self) -> Result<()> {
        let Some((tab, comps)) = &self.gain else { return Ok(()) };
        for c in comps {
            if self.idle_2d(c.comp) {
                continue;
            }
            let args = Args::new()
                .p(self.new_ptr(c.comp))
                .p(c.idx.cu_deviceptr())
                .p(c.row.cu_deviceptr())
                .p(tab.cu_deviceptr())
                .p(c.scale.cu_deviceptr())
                .p(c.prev.cu_deviceptr())
                .p(c.dp.cu_deviceptr())
                .p(c.pop.cu_deviceptr())
                .u(c.n as u32);
            self.launch_1d(&self.k.gain_post, c.n, args)?;
        }
        Ok(())
    }

    /// Off-diagonal tensors: save E^n over the interior plane range.
    fn tensor_save_launch(&self) -> Result<()> {
        let (Some(td), Some(t)) = (&self.tensor, &self.plan.tensor) else { return Ok(()) };
        let plane = self.plan.plane();
        let n = (t.i1 - t.i0) * plane;
        for a in 0..3 {
            let dst = td.en[a].cu_deviceptr() + ((t.i0 - t.p0) * plane * 4) as u64;
            let src = self.e[a].cu_deviceptr() + (t.i0 * plane * 4) as u64;
            unsafe { memcpy_dtod_async(dst, src, n * 4, self.stream.cu_stream()) }.map_err(|e| anyhow!("{e:?}"))?;
        }
        Ok(())
    }

    /// Off-diagonal tensors: dD = (E_lin - E^n) cdt / cb over the interior range.
    fn tensor_dd_launch(&self) -> Result<()> {
        let (Some(td), Some(t)) = (&self.tensor, &self.plan.tensor) else { return Ok(()) };
        let plane = self.plan.plane();
        let n = (t.i1 - t.i0) * plane;
        for a in 0..3 {
            let off = ((t.i0 - t.p0) * plane * 4) as u64;
            let (ca_ptr, has_ca) = match &self.ca {
                Some(c) => (c[a].cu_deviceptr(), 1u32),
                None => (self.dummy.cu_deviceptr(), 0u32),
            };
            let args = Args::new()
                .p(self.new_ptr(Component::e(a)))
                .p(td.prev[a].cu_deviceptr() + off)
                .p(td.en[a].cu_deviceptr() + off)
                .p(self.cb[a].cu_deviceptr())
                .p(ca_ptr)
                .u(has_ca)
                .f(t.cdt)
                .u64((t.i0 * plane) as u64)
                .u64(n as u64);
            self.launch_1d(&self.k.tensor_dd, n, args)?;
        }
        Ok(())
    }

    /// Off-diagonal tensors: E_a += kappa_ab <dD_b> + kappa_ac <dD_c>.
    fn tensor_apply_launch(&self) -> Result<()> {
        let (Some(td), Some(t)) = (&self.tensor, &self.plan.tensor) else { return Ok(()) };
        for (ci, (comp, n, idx, c1, c2, m1, m2)) in td.comps.iter().enumerate() {
            let a = comp.axis();
            let (opm, oscale, ost, osp) = &td.ops[ci];
            let args = Args::new()
                .p(self.new_ptr(Component::e(a)))
                .p(idx.cu_deviceptr())
                .p(c1.cu_deviceptr())
                .p(c2.cu_deviceptr())
                .p(td.prev[(a + 1) % 3].cu_deviceptr())
                .p(td.prev[(a + 2) % 3].cu_deviceptr())
                .p(m1.cu_deviceptr())
                .p(m2.cu_deviceptr())
                .p(td.en[(a + 1) % 3].cu_deviceptr())
                .p(td.en[(a + 2) % 3].cu_deviceptr())
                .u(t.lossy as u32)
                .p(td.en[a].cu_deviceptr())
                .p(opm.cu_deviceptr())
                .p(oscale.cu_deviceptr())
                .p(td.optab.cu_deviceptr())
                .u(t.op_np as u32)
                .p(ost.cu_deviceptr())
                .p(osp.cu_deviceptr())
                .u(*n as u32)
                .u(a as u32)
                .u(self.plan.ny() as u32)
                .u(self.plan.nz() as u32)
                .u(t.p0 as u32)
                .u(t.p1 as u32)
                .u(t.wrap);
            self.launch_1d(&self.k.tensor_apply, *n, args)?;
        }
        Ok(())
    }

    /// Gyrotropic poles: P update from E^n and E_a -= dP_a / eps_inf.
    fn gyro_apply_launch(&self) -> Result<()> {
        let (Some(td), Some(t)) = (&self.tensor, &self.plan.tensor) else { return Ok(()) };
        for (a, n, idx, row, scale, p, pp) in &td.gyro {
            let a = *a;
            let args = Args::new()
                .p(self.new_ptr(Component::e(a)))
                .p(idx.cu_deviceptr())
                .p(td.en[a].cu_deviceptr())
                .p(td.en[(a + 1) % 3].cu_deviceptr())
                .p(td.en[(a + 2) % 3].cu_deviceptr())
                .p(row.cu_deviceptr())
                .p(scale.cu_deviceptr())
                .p(td.gyro_tab.cu_deviceptr())
                .u(t.gyro_np as u32)
                .p(p.cu_deviceptr())
                .p(pp.cu_deviceptr())
                .u(*n as u32)
                .u(a as u32)
                .u(self.plan.ny() as u32)
                .u(self.plan.nz() as u32)
                .u(t.p0 as u32)
                .u(t.p1 as u32)
                .u(t.wrap);
            self.launch_1d(&self.k.gyro_apply, *n, args)?;
        }
        Ok(())
    }

    /// Dense dispersive update of the deferred x-plane 0 (the fused kernel
    /// does every other plane inline; E^n in A, E^{n+1} in B).
    fn disp_dense_launch(&self) -> Result<()> {
        let Some(d) = &self.disp_dense else { return Ok(()) };
        if self.fused.as_ref().map(|f| f.ghost_lo) != Some(1) {
            return Ok(());
        }
        let plane = self.plan.plane();
        let n = plane;
        let len = self.plan.storage_len();
        for (a, dm, p, pp, scale, dmu) in &d.comps {
            let comp = Component::e(*a);
            let args = Args::new()
                .p(self.field_ptr(comp))
                .p(self.new_ptr(comp))
                .p(dm.cu_deviceptr())
                .p(p.cu_deviceptr())
                .p(pp.cu_deviceptr())
                .p(d.coefs.cu_deviceptr())
                .p(scale.cu_deviceptr())
                .u(d.npole as u32)
                .u64(plane as u64)
                .u64(n as u64)
                .u64(len as u64)
                .u(*dmu);
            self.launch_1d(&self.k.disp_dense, n, args)?;
        }
        Ok(())
    }

    fn bc_packed(&self) -> u32 {
        let p = &self.plan;
        p.bc_y[0] | (p.bc_y[1] << 4) | (p.bc_z[0] << 8) | (p.bc_z[1] << 12)
    }

    fn fused_step(&self) -> Result<()> {
        self.disp_update_launch()?;
        let f = self.fused.as_ref().unwrap();
        if f.twod.is_some() {
            return self.step2d_launch();
        }
        let p = &self.plan;
        let (nx, ny, nz) = (p.nxl as u32, p.ny() as u32, p.nz() as u32);
        let rd = &f.psi_h[self.cur_psi];
        let wr = &f.psi_h[1 - self.cur_psi];
        let args = Args::new()
            .p(self.e[0].cu_deviceptr())
            .p(self.e[1].cu_deviceptr())
            .p(self.e[2].cu_deviceptr())
            .p(self.h[0].cu_deviceptr())
            .p(self.h[1].cu_deviceptr())
            .p(self.h[2].cu_deviceptr())
            .p(f.eb[0].cu_deviceptr())
            .p(f.eb[1].cu_deviceptr())
            .p(f.eb[2].cu_deviceptr())
            .p(f.hb[0].cu_deviceptr())
            .p(f.hb[1].cu_deviceptr())
            .p(f.hb[2].cu_deviceptr())
            .p(f.mat.cu_deviceptr())
            .p(f.tab.cu_deviceptr())
            .u(f.lossy)
            .f(p.ch_scalar)
            .p(self.inv_p[0].cu_deviceptr())
            .p(self.inv_p[1].cu_deviceptr())
            .p(self.inv_p[2].cu_deviceptr())
            .p(self.inv_d[0].cu_deviceptr())
            .p(self.inv_d[1].cu_deviceptr())
            .p(self.inv_d[2].cu_deviceptr())
            .u(nx)
            .u(ny)
            .u(nz)
            .u(self.bc_packed())
            .u(f.ghost_lo)
            .u(f.chunk)
            .u(f.pml_n[0])
            .u(f.pml_n[1])
            .u(f.pml_n[2])
            .p(f.prof[0].cu_deviceptr())
            .p(f.prof[1].cu_deviceptr())
            .p(f.prof[2].cu_deviceptr())
            .p(f.psi_e[0].cu_deviceptr())
            .p(f.psi_e[1].cu_deviceptr())
            .p(f.psi_e[2].cu_deviceptr())
            .p(rd[0].cu_deviceptr())
            .p(rd[1].cu_deviceptr())
            .p(rd[2].cu_deviceptr())
            .p(wr[0].cu_deviceptr())
            .p(wr[1].cu_deviceptr())
            .p(wr[2].cu_deviceptr())
            .u(f.mat_mode);
        // dense dispersive state, per E component (dummy pointers when off)
        let dz = self.dummy.cu_deviceptr();
        let mut dd = [[dz; 4]; 3];
        let mut dmu = 0u32;
        let (mut npole, mut coefs) = (0u32, dz);
        if let Some(d) = &self.disp_dense {
            npole = d.npole as u32;
            coefs = d.coefs.cu_deviceptr();
            for (a, dm, p, pp, scale, u) in &d.comps {
                dd[*a] = [dm.cu_deviceptr(), p.cu_deviceptr(), pp.cu_deviceptr(), scale.cu_deviceptr()];
                dmu |= (1 << (24 + *a)) | (*u << (8 * *a));
            }
        }
        let mut args = args;
        for q in 0..3 {
            for a in 0..3 {
                args = args.p(dd[a][q]);
            }
        }
        let args = args.p(coefs).p(dd[0][3]).p(dd[1][3]).p(dd[2][3]).u(npole).u(dmu);
        // the other part of complex fields: current fields and H-side CPML
        // state (the plain kernel ignores these)
        let (eo, ho) = self.partner_ptrs();
        let so = match &f.imag {
            Some(im) => {
                let q = &im.psi_h[self.cur_psi];
                [q[0].cu_deviceptr(), q[1].cu_deviceptr(), q[2].cu_deviceptr()]
            }
            None => [dz; 3],
        };
        let args = args
            .p(eo[0])
            .p(eo[1])
            .p(eo[2])
            .p(ho[0])
            .p(ho[1])
            .p(ho[2])
            .p(so[0])
            .p(so[1])
            .p(so[2])
            .f(p.bloch_phase[1].0 as f32)
            .f(self.bsign[1])
            .f(p.bloch_phase[2].0 as f32)
            .f(self.bsign[2]);
        let kernel = if f.imag.is_some() { &self.k.step_fused_bloch } else { &self.k.step_fused };
        let (bk, bj) = f.tile;
        let grid = (nz.div_ceil(bk), ny.div_ceil(bj), nx.div_ceil(f.chunk));
        let smem = 24 * (bk + 1) * (bj + 1);
        let mut slots = args.0;
        let mut ptrs: Vec<*mut c_void> = slots.iter_mut().map(|s| s as *mut u64 as *mut c_void).collect();
        unsafe { launch_kernel_on_stream(kernel, grid, (bk, bj, 1), smem, &self.stream, &mut ptrs) }
            .map_err(|e| anyhow!("kernel launch failed: {e:?}"))
    }

